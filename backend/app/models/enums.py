from enum import Enum

class UserRole(str, Enum):
    CONSUMER = "CONSUMER"
    BUSINESS_ADMIN = "BUSINESS_ADMIN"
    CARE_RECIPIENT = "CARE_RECIPIENT"
    CAREGIVER = "CAREGIVER"
    ORGANIZER = "ORGANIZER"

class TransactionLifecycleState(str, Enum):
    DRAFT = "DRAFT"
    PROPOSED = "PROPOSED"
    POLICY_CHECK = "POLICY_CHECK"
    AWAITING_APPROVAL = "AWAITING_APPROVAL"
    APPROVED = "APPROVED"
    PAYMENT_PENDING = "PAYMENT_PENDING"
    PAID = "PAID"
    REJECTED = "REJECTED"
    EXPIRED = "EXPIRED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"

class ModuleScope(str, Enum):
    PERSONAL = "PERSONAL"
    BUSINESS = "BUSINESS"
    COLLECTIVE = "COLLECTIVE"
    CARE = "CARE"

class PolicyDecision(str, Enum):
    ALLOW = "ALLOW"
    REQUIRE_APPROVAL = "REQUIRE_APPROVAL"
    DENY = "DENY"

class ApprovalMode(str, Enum):
    EXPLICIT_ALWAYS = "EXPLICIT_ALWAYS"      # Mode A: Every single order requires human confirmation
    CONTROLLED_AUTO = "CONTROLLED_AUTO"      # Mode B: Bounded auto-reorder if all conditions met

class ApprovalType(str, Enum):
    USER_DIRECT = "USER_DIRECT"
    GUARDIAN_DELEGATED = "GUARDIAN_DELEGATED"
    POLICY_AUTOMATIC = "POLICY_AUTOMATIC"

class AuditEventType(str, Enum):
    PROPOSAL_CREATED = "PROPOSAL_CREATED"
    POLICY_EVALUATED = "POLICY_EVALUATED"
    FINGERPRINT_GENERATED = "FINGERPRINT_GENERATED"
    APPROVAL_GRANTED = "APPROVAL_GRANTED"
    APPROVAL_REVOKED = "APPROVAL_REVOKED"
    APPROVAL_INVALIDATED = "APPROVAL_INVALIDATED"
    STATE_TRANSITION = "STATE_TRANSITION"
    PAYPAL_ORDER_CREATED = "PAYPAL_ORDER_CREATED"
    PAYPAL_ORDER_CAPTURED = "PAYPAL_ORDER_CAPTURED"
    TAMPER_DETECTED = "TAMPER_DETECTED"
    SECURITY_BLOCK = "SECURITY_BLOCK"

class SeverityLevel(str, Enum):
    INFO = "INFO"
    SUCCESS = "SUCCESS"
    WARNING = "WARNING"
    ALERT = "ALERT"

class ReservationStatus(str, Enum):
    HELD = "HELD"
    CONSUMED = "CONSUMED"
    RELEASED = "RELEASED"
